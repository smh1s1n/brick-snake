import 'package:flutter/material.dart';

/// Authentic 3x5 and 5x7 dot-matrix bitmap font renderer for Nokia LCD screen.
class LcdFont {
  // 3x5 compact digit and letter patterns (1 = pixel on, 0 = pixel off)
  // Each row has 3 bits, 5 rows total
  static const Map<String, List<int>> glyphs3x5 = {
    '0': [0x7, 0x5, 0x5, 0x5, 0x7],
    '1': [0x2, 0x6, 0x2, 0x2, 0x7],
    '2': [0x7, 0x1, 0x7, 0x4, 0x7],
    '3': [0x7, 0x1, 0x7, 0x1, 0x7],
    '4': [0x5, 0x5, 0x7, 0x1, 0x1],
    '5': [0x7, 0x4, 0x7, 0x1, 0x7],
    '6': [0x7, 0x4, 0x7, 0x5, 0x7],
    '7': [0x7, 0x1, 0x2, 0x2, 0x2],
    '8': [0x7, 0x5, 0x7, 0x5, 0x7],
    '9': [0x7, 0x5, 0x7, 0x1, 0x7],
    'A': [0x2, 0x5, 0x7, 0x5, 0x5],
    'B': [0x6, 0x5, 0x6, 0x5, 0x6],
    'C': [0x3, 0x4, 0x4, 0x4, 0x3],
    'D': [0x6, 0x5, 0x5, 0x5, 0x6],
    'E': [0x7, 0x4, 0x6, 0x4, 0x7],
    'F': [0x7, 0x4, 0x6, 0x4, 0x4],
    'G': [0x3, 0x4, 0x5, 0x5, 0x3],
    'H': [0x5, 0x5, 0x7, 0x5, 0x5],
    'I': [0x7, 0x2, 0x2, 0x2, 0x7],
    'J': [0x1, 0x1, 0x1, 0x5, 0x2],
    'K': [0x5, 0x5, 0x6, 0x5, 0x5],
    'L': [0x4, 0x4, 0x4, 0x4, 0x7],
    'M': [0x5, 0x7, 0x5, 0x5, 0x5],
    'N': [0x6, 0x5, 0x5, 0x5, 0x5],
    'O': [0x2, 0x5, 0x5, 0x5, 0x2],
    'P': [0x6, 0x5, 0x6, 0x4, 0x4],
    'Q': [0x2, 0x5, 0x5, 0x6, 0x3],
    'R': [0x6, 0x5, 0x6, 0x5, 0x5],
    'S': [0x3, 0x4, 0x2, 0x1, 0x6],
    'T': [0x7, 0x2, 0x2, 0x2, 0x2],
    'U': [0x5, 0x5, 0x5, 0x5, 0x7],
    'V': [0x5, 0x5, 0x5, 0x5, 0x2],
    'W': [0x5, 0x5, 0x5, 0x7, 0x5],
    'X': [0x5, 0x5, 0x2, 0x5, 0x5],
    'Y': [0x5, 0x5, 0x2, 0x2, 0x2],
    'Z': [0x7, 0x1, 0x2, 0x4, 0x7],
    ':': [0x0, 0x2, 0x0, 0x2, 0x0],
    '-': [0x0, 0x0, 0x7, 0x0, 0x0],
    '.': [0x0, 0x0, 0x0, 0x0, 0x2],
    '!': [0x2, 0x2, 0x2, 0x0, 0x2],
    '?': [0x6, 0x1, 0x2, 0x0, 0x2],
    '/': [0x1, 0x1, 0x2, 0x4, 0x4],
    ' ': [0x0, 0x0, 0x0, 0x0, 0x0],
    '>': [0x4, 0x2, 0x1, 0x2, 0x4],
    '<': [0x1, 0x2, 0x4, 0x2, 0x1],
    '#': [0x5, 0x7, 0x5, 0x7, 0x5],
  };

  /// Draws pixel-perfect bitmap string onto canvas at [origin] using given [pixelSize].
  static void drawText(
    Canvas canvas, {
    required String text,
    required Offset origin,
    required double pixelSize,
    required Color color,
    int spacing = 1,
  }) {
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.fill;

    double currentX = origin.dx;
    final upper = text.toUpperCase();

    for (int c = 0; c < upper.length; c++) {
      final char = upper[c];
      final glyph = glyphs3x5[char] ?? glyphs3x5[' '];

      if (glyph != null) {
        for (int row = 0; row < 5; row++) {
          final rowBits = glyph[row];
          for (int col = 0; col < 3; col++) {
            final bit = (rowBits >> (2 - col)) & 1;
            if (bit == 1) {
              canvas.drawRect(
                Rect.fromLTWH(
                  currentX + (col * pixelSize),
                  origin.dy + (row * pixelSize),
                  pixelSize,
                  pixelSize,
                ),
                paint,
              );
            }
          }
        }
      }
      currentX += (3 + spacing) * pixelSize;
    }
  }

  static double measureWidth(String text, double pixelSize, {int spacing = 1}) {
    return text.length * ((3 + spacing) * pixelSize) - (spacing * pixelSize);
  }
}
